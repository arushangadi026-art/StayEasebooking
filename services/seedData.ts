/**
 * Seeds preloaded fictional academic demonstration data ONLY if JSON files do not already exist.
 * Never overwrites existing JSON records on server restart.
 */
export async function initializeDataStore(): Promise<void> {
  await ensureDataDir();

  if (!(await dataFileExists('hotels.json'))) {
    await writeJson('hotels.json', buildInitialHotels());
  }
  if (!(await dataFileExists('rooms.json'))) {
    await writeJson('rooms.json', buildInitialRooms());
  }
  if (!(await dataFileExists('users.json'))) {
    const users = await buildInitialUsers();
    await writeJson('users.json', users);
  }
  if (!(await dataFileExists('bookings.json'))) {
    await writeJson('bookings.json', buildInitialBookings());
  }
  if (!(await dataFileExists('reviews.json'))) {
    await writeJson('reviews.json', buildInitialReviews());
  }
  if (!(await dataFileExists('eventRegistrations.json'))) {
    await writeJson('eventRegistrations.json', buildInitialEventRegistrations());
  }
  if (!(await dataFileExists('messages.json'))) {
    await writeJson('messages.json', buildInitialMessages());
  }
}
